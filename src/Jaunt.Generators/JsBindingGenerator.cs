using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Jaunt.Generators;

/// <summary>
/// Generates AOT-safe <c>JsTypeInfo&lt;T&gt;</c> descriptors for every <c>[JsSerializable(typeof(T))]</c> on a partial
/// class deriving from <c>Jaunt.JsBindingContext</c>. The generated code references members statically (no
/// reflection, no runtime code generation). Unsupported member types are build errors, never silent fallbacks.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class JsBindingGenerator : IIncrementalGenerator
{
    private const string SerializableAttr = "Jaunt.JsSerializableAttribute";
    private const string NameAttr = "Jaunt.JsPropertyNameAttribute";
    private const string IgnoreAttr = "Jaunt.JsIgnoreAttribute";

    internal static readonly DiagnosticDescriptor NotPartial = new(
        "JAUNT001", "Binding context must be partial", "Binding context '{0}' must be declared partial", "Jaunt.Bindings", DiagnosticSeverity.Error, true);
    internal static readonly DiagnosticDescriptor NotContext = new(
        "JAUNT002", "Binding context must derive from JsBindingContext", "Binding context '{0}' must derive from Jaunt.JsBindingContext", "Jaunt.Bindings", DiagnosticSeverity.Error, true);
    internal static readonly DiagnosticDescriptor UnsupportedMember = new(
        "JAUNT003", "Unsupported member type", "Member '{0}.{1}' has type '{2}', which has no Jaunt mapping; add [JsSerializable(typeof({2}))] for DTOs, use a supported type, or mark it [JsIgnore]",
        "Jaunt.Bindings", DiagnosticSeverity.Error, true);
    internal static readonly DiagnosticDescriptor NameCollision = new(
        "JAUNT004", "JS member name collision", "Members of '{0}' map to the same JS name '{1}'", "Jaunt.Bindings", DiagnosticSeverity.Error, true);
    internal static readonly DiagnosticDescriptor NoConstructor = new(
        "JAUNT005", "No usable constructor", "Type '{0}' needs a public parameterless constructor with settable members or a public constructor whose parameters match its members",
        "Jaunt.Bindings", DiagnosticSeverity.Error, true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var contexts = context.SyntaxProvider.ForAttributeWithMetadataName(
            SerializableAttr,
            static (node, _) => node is ClassDeclarationSyntax,
            static (ctx, _) => (INamedTypeSymbol)ctx.TargetSymbol);
        context.RegisterSourceOutput(contexts.Collect(), static (spc, symbols) =>
        {
            foreach (var sym in symbols.Distinct<INamedTypeSymbol>(SymbolEqualityComparer.Default))
                Generate(spc, sym);
        });
    }

    private sealed class Member
    {
        public string ClrName = "";
        public string JsName = "";
        public ITypeSymbol Type = null!;
        public bool Settable;
        public string InfoExpr = "";
        public bool Optional;
    }

    private static void Generate(SourceProductionContext spc, INamedTypeSymbol ctx)
    {
        var loc = ctx.Locations.FirstOrDefault();
        bool isPartial = ctx.DeclaringSyntaxReferences.Any(r => r.GetSyntax() is ClassDeclarationSyntax c && c.Modifiers.Any(m => m.Text == "partial"));
        if (!isPartial) { spc.ReportDiagnostic(Diagnostic.Create(NotPartial, loc, ctx.Name)); return; }
        bool derives = false;
        for (var b = ctx.BaseType; b != null; b = b.BaseType)
            if (b.ToDisplayString() == "Jaunt.JsBindingContext") derives = true;
        if (!derives) { spc.ReportDiagnostic(Diagnostic.Create(NotContext, loc, ctx.Name)); return; }

        var types = new List<INamedTypeSymbol>();
        foreach (var a in ctx.GetAttributes())
        {
            if (a.AttributeClass?.ToDisplayString() != SerializableAttr) continue;
            if (a.ConstructorArguments.Length == 1 && a.ConstructorArguments[0].Value is INamedTypeSymbol t && !types.Contains(t, SymbolEqualityComparer.Default))
                types.Add(t);
        }
        var known = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var t in types) known[t.ToDisplayString()] = PropName(t);

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/> Jaunt.Generators: AOT-safe JsTypeInfo descriptors (static member access only).");
        sb.AppendLine("#nullable enable annotations");
        sb.AppendLine("#nullable disable warnings");
        if (!ctx.ContainingNamespace.IsGlobalNamespace) sb.Append("namespace ").Append(ctx.ContainingNamespace.ToDisplayString()).AppendLine(";");
        sb.AppendLine();
        sb.Append(Accessibility(ctx)).Append(" partial class ").Append(ctx.Name).AppendLine();
        sb.AppendLine("{");
        sb.Append("    /// <summary>Shared instance.</summary>\n    public static ").Append(ctx.Name).Append(" Default { get; } = new ").Append(ctx.Name).AppendLine("();");
        bool ok = true;
        foreach (var t in types)
        {
            string fq = "global::" + t.ToDisplayString();
            string prop = PropName(t);
            var members = CollectMembers(spc, t, known, ref ok);
            if (members == null) { ok = false; continue; }
            var dup = members.GroupBy(m => m.JsName).FirstOrDefault(g => g.Count() > 1);
            if (dup != null) { spc.ReportDiagnostic(Diagnostic.Create(NameCollision, loc, t.Name, dup.Key)); ok = false; continue; }
            string? factory = BuildFactory(t, members, fq);
            if (factory == null) { spc.ReportDiagnostic(Diagnostic.Create(NoConstructor, loc, t.Name)); ok = false; continue; }

            sb.AppendLine();
            sb.Append("    private global::Jaunt.JsTypeInfo<").Append(fq).Append(">? _").Append(prop).AppendLine(";");
            sb.Append("    /// <summary>Descriptor for <see cref=\"").Append(fq.Replace("global::", "")).AppendLine("\"/>.</summary>");
            sb.Append("    public global::Jaunt.JsTypeInfo<").Append(fq).Append("> ").Append(prop)
              .Append(" => _").Append(prop).Append(" ??= Create").Append(prop).AppendLine("();");
            sb.Append("    private global::Jaunt.JsTypeInfo<").Append(fq).Append("> Create").Append(prop).AppendLine("() =>");
            sb.Append("        global::Jaunt.JsTypeInfo.Object<").Append(fq).AppendLine(">()");
            foreach (var m in members)
                sb.Append("            .Property(\"").Append(m.JsName).Append("\", static x => x.").Append(m.ClrName).Append(", ").Append(m.InfoExpr).AppendLine("!)");
            sb.Append("            .Factory(").Append(factory).AppendLine(")");
            sb.AppendLine("            .Build();");
        }
        sb.AppendLine("}");
        if (ok || types.Count > 0)
            spc.AddSource(ctx.Name + ".JsBindings.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    private static string Accessibility(INamedTypeSymbol t) => t.DeclaredAccessibility switch
    {
        Microsoft.CodeAnalysis.Accessibility.Public => "public",
        Microsoft.CodeAnalysis.Accessibility.Internal => "internal",
        _ => "internal",
    };

    private static string PropName(INamedTypeSymbol t) => t.Name;

    private static string CamelCase(string s) => s.Length == 0 || char.IsLower(s[0]) ? s : char.ToLowerInvariant(s[0]) + s.Substring(1);

    private static List<Member>? CollectMembers(SourceProductionContext spc, INamedTypeSymbol t, Dictionary<string, string> known, ref bool ok)
    {
        var list = new List<Member>();
        bool failed = false;
        foreach (var sym in t.GetMembers())
        {
            if (sym is not IPropertySymbol p || p.IsStatic || p.IsIndexer || p.DeclaredAccessibility != Microsoft.CodeAnalysis.Accessibility.Public || p.GetMethod == null) continue;
            if (p.GetAttributes().Any(a => a.AttributeClass?.ToDisplayString() == IgnoreAttr)) continue;
            if (p.Name == "EqualityContract") continue;
            string jsName = CamelCase(p.Name);
            var nameAttr = p.GetAttributes().FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == NameAttr);
            if (nameAttr != null && nameAttr.ConstructorArguments.Length == 1 && nameAttr.ConstructorArguments[0].Value is string n) jsName = n;
            var info = InfoFor(p.Type, known, out bool optional);
            if (info == null)
            {
                spc.ReportDiagnostic(Diagnostic.Create(UnsupportedMember, p.Locations.FirstOrDefault(), t.Name, p.Name, p.Type.ToDisplayString()));
                failed = true;
                continue;
            }
            list.Add(new Member
            {
                ClrName = p.Name,
                JsName = jsName,
                Type = p.Type,
                Settable = p.SetMethod != null && p.SetMethod.DeclaredAccessibility == Microsoft.CodeAnalysis.Accessibility.Public,
                InfoExpr = info,
                Optional = optional,
            });
        }
        return failed ? null : list;
    }

    /// <summary>Maps a CLR type to a JsTypeInfo expression; null when unsupported.</summary>
    private static string? InfoFor(ITypeSymbol type, Dictionary<string, string> known, out bool optional)
    {
        optional = type.NullableAnnotation == NullableAnnotation.Annotated;
        if (type is INamedTypeSymbol nt && nt.IsGenericType && nt.ConstructedFrom.SpecialType == SpecialType.System_Nullable_T)
        {
            optional = true;
            var inner = InfoFor(nt.TypeArguments[0], known, out _);
            return inner == null ? null : "global::Jaunt.JsTypeInfo.Nullable(" + inner + ")";
        }
        switch (type.SpecialType)
        {
            case SpecialType.System_String: return "global::Jaunt.JsTypeInfo.String";
            case SpecialType.System_Int32: return "global::Jaunt.JsTypeInfo.Int32";
            case SpecialType.System_Int64: return "global::Jaunt.JsTypeInfo.Int64";
            case SpecialType.System_Double: return "global::Jaunt.JsTypeInfo.Double";
            case SpecialType.System_Boolean: return "global::Jaunt.JsTypeInfo.Boolean";
        }
        string display = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        if (display == "global::System.DateTimeOffset") return "global::Jaunt.JsTypeInfo.IsoDateTime";
        if (type is IArrayTypeSymbol at && at.Rank == 1)
        {
            var inner = InfoFor(at.ElementType, known, out _);
            return inner == null ? null : "global::Jaunt.JsTypeInfo.Array(" + inner + ")";
        }
        if (type is INamedTypeSymbol g && g.IsGenericType)
        {
            string def = g.ConstructedFrom.ToDisplayString();
            if (def == "System.Collections.Generic.List<T>")
            {
                var inner = InfoFor(g.TypeArguments[0], known, out _);
                return inner == null ? null : "global::Jaunt.JsTypeInfo.List(" + inner + ")";
            }
            if (def == "System.Collections.Generic.Dictionary<TKey, TValue>" && g.TypeArguments[0].SpecialType == SpecialType.System_String)
            {
                var inner = InfoFor(g.TypeArguments[1], known, out _);
                return inner == null ? null : "global::Jaunt.JsTypeInfo.Dictionary(" + inner + ")";
            }
        }
        var plain = type.WithNullableAnnotation(NullableAnnotation.NotAnnotated).ToDisplayString();
        if (known.TryGetValue(plain, out var prop))
            return "global::Jaunt.JsTypeInfo.Lazy<global::" + plain + ">(() => this." + prop + ")";
        return null;
    }

    private static string? BuildFactory(INamedTypeSymbol t, List<Member> members, string fq)
    {
        string Read(Member m) => m.Optional
            ? "r.Optional(\"" + m.JsName + "\", " + m.InfoExpr + ")"
            : "r.Required(\"" + m.JsName + "\", " + m.InfoExpr + ")!";
        var ctors = t.InstanceConstructors.Where(c => c.DeclaredAccessibility == Microsoft.CodeAnalysis.Accessibility.Public).ToList();
        // positional constructor whose parameters all match members (records, immutable DTOs)
        foreach (var c in ctors.OrderByDescending(c => c.Parameters.Length))
        {
            if (c.Parameters.Length == 0) continue;
            var args = new List<string>();
            var used = new HashSet<Member>();
            bool match = true;
            foreach (var p in c.Parameters)
            {
                var m = members.FirstOrDefault(x => string.Equals(x.ClrName, p.Name, StringComparison.OrdinalIgnoreCase));
                if (m == null) { match = false; break; }
                used.Add(m);
                args.Add(Read(m));
            }
            if (!match) continue;
            var rest = members.Where(m => !used.Contains(m) && m.Settable).ToList();
            var init = rest.Count == 0 ? "" : " { " + string.Join(", ", rest.Select(m => m.ClrName + " = " + Read(m))) + " }";
            return "r => new " + fq + "(" + string.Join(", ", args) + ")" + init;
        }
        if (ctors.Any(c => c.Parameters.Length == 0))
        {
            var settable = members.Where(m => m.Settable).ToList();
            return "r => new " + fq + "() { " + string.Join(", ", settable.Select(m => m.ClrName + " = " + Read(m))) + " }";
        }
        return null;
    }
}
