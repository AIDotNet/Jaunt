#!/usr/bin/env python3
"""Generates src/Jaunt/Runtime/CaseMapping.g.cs: full Unicode case mappings for String.prototype.toLowerCase /
toUpperCase (ECMA-262 §22.1.3.28 / .30: the locale-independent mappings of UnicodeData.txt and the unconditional
entries of SpecialCasing.txt; the Final_Sigma condition is implemented in code).

Usage: python3 tools/unicode/casing.py   (downloads are shared with generate.py's cache)
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import generate  # noqa: E402

generate.FILES["UnicodeData.txt"] = generate.UCD + "UnicodeData.txt"
generate.FILES["SpecialCasing.txt"] = generate.UCD + "SpecialCasing.txt"

OUT = os.path.join(generate.ROOT, "src", "Jaunt", "Runtime", "CaseMapping.g.cs")


def load():
    lower, upper = {}, {}
    for fields in generate.data_lines("UnicodeData.txt"):
        cp = int(fields[0], 16)
        if fields[12]:
            upper[cp] = [int(fields[12], 16)]
        if fields[13]:
            lower[cp] = [int(fields[13], 16)]
    # UnicodeData.txt lists ranges (First/Last) only for characters without case mappings
    for fields in generate.data_lines("SpecialCasing.txt"):
        if len(fields) > 4 and fields[4].strip():
            continue  # conditional (language or context) mappings: Final_Sigma is handled in code
        cp = int(fields[0], 16)
        lo = [int(x, 16) for x in fields[1].split()]
        up = [int(x, 16) for x in fields[3].split()]
        lower[cp] = lo
        upper[cp] = up
    lower = {k: v for k, v in lower.items() if v != [k]}
    upper = {k: v for k, v in upper.items() if v != [k]}
    return lower, upper


def utf16(cps):
    out = []
    for cp in cps:
        if cp >= 0x10000:
            cp -= 0x10000
            out += [0xD800 + (cp >> 10), 0xDC00 + (cp & 0x3FF)]
        else:
            out.append(cp)
    return "".join(f"\\u{u:04X}" for u in out)


def table(name, mapping):
    keys = sorted(mapping)
    lines = [f"    internal static readonly int[] {name}Keys =", "    {"]
    for i in range(0, len(keys), 12):
        lines.append("        " + ", ".join(f"0x{k:X}" for k in keys[i:i + 12]) + ",")
    lines += ["    };", f"    internal static readonly string[] {name}Values =", "    {"]
    for i in range(0, len(keys), 8):
        lines.append("        " + ", ".join(f'"{utf16(mapping[k])}"' for k in keys[i:i + 8]) + ",")
    lines.append("    };")
    return "\n".join(lines)


def main():
    lower, upper = load()
    text = "\n".join([
        "// <auto-generated> by tools/unicode/casing.py from the Unicode Character Database "
        f"{generate.UNICODE_VERSION}; do not edit. </auto-generated>",
        "// Unicode data: Copyright © Unicode, Inc. License: https://www.unicode.org/license.txt (see THIRD_PARTY_NOTICES.md)",
        "namespace Jaunt.Runtime;",
        "",
        "internal static partial class CaseMapping",
        "{",
        f'    internal const string UnicodeVersion = "{generate.UNICODE_VERSION}";',
        table("Lower", lower),
        table("Upper", upper),
        "}",
        "",
    ])
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {OUT}: {len(lower)} lower, {len(upper)} upper mappings", file=sys.stderr)


if __name__ == "__main__":
    main()
